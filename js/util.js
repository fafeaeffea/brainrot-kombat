function hex2rgb(h) {
  h = h.replace('#', '');
  if (h.length === 3) h = h.split('').map(c => c + c).join('');
  const n = parseInt(h, 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}
function rgb2hex(r, g, b) {
  return '#' + ((1 << 24) | (clamp(r | 0, 0, 255) << 16) | (clamp(g | 0, 0, 255) << 8) | clamp(b | 0, 0, 255)).toString(16).slice(1);
}
function mix(a, b, t) {
  const A = hex2rgb(a), B = hex2rgb(b);
  return rgb2hex(lerp(A[0], B[0], t), lerp(A[1], B[1], t), lerp(A[2], B[2], t));
}
// Тени уходят в фиолетовый, блики в тёплый — палитра как в пиксель-арте
const _shadeCache = {};
function shade(h, f) {
  const k = h + f;
  let v = _shadeCache[k];
  if (v) return v;
  v = f < 0 ? mix(h, '#140a26', -f) : mix(h, '#fff8dc', f);
  _shadeCache[k] = v;
  return v;
}
const _c32 = {};
function c32(h, a = 255) {
  const k = h + a;
  let v = _c32[k];
  if (v === undefined) {
    const [r, g, b] = hex2rgb(h);
    v = _c32[k] = ((a << 24) | (b << 16) | (g << 8) | r) >>> 0;
  }
  return v;
}
function mkCanvas(w, h) {
  const cv = document.createElement('canvas');
  cv.width = w; cv.height = h;
  const ctx = cv.getContext('2d');
  ctx.imageSmoothingEnabled = false;
  return [cv, ctx];
}

