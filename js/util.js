function textWidth(str, s = 1) {
  let w = 0;
  for (const ch of str.toUpperCase()) { const g = GLYPHS[ch] || GLYPHS['?']; w += (g.w + 1) * s; }
  return Math.max(0, w - s);
}
const _txt = new Map();
// fill: цвет или [верх, низ] — вертикальный градиент
function textSprite(str, s, fill, outline = '#000', shadow = '#000') {
  const key = str + '|' + s + '|' + fill + '|' + outline + '|' + shadow;
  let cv = _txt.get(key);
  if (cv) return cv;
  str = str.toUpperCase();
  const tw = textWidth(str, s), th = 7 * s;
  const pad = 2, w = tw + pad * 2 + 1, h = th + pad * 2 + 1;
  const mask = new Uint8Array(w * h);
  let x = pad;
  for (const ch of str) {
    const g = GLYPHS[ch] || GLYPHS['?'];
    for (let r = 0; r < 7; r++) for (let c = 0; c < g.w; c++) {
      if (g.rows[r][g.x0 + c] === '#')
        for (let yy = 0; yy < s; yy++) for (let xx = 0; xx < s; xx++)
          mask[(pad + r * s + yy) * w + x + c * s + xx] = 1;
    }
    x += (g.w + 1) * s;
  }
  let ctx;
  [cv, ctx] = mkCanvas(w, h);
  const img = ctx.createImageData(w, h), d = new Uint32Array(img.data.buffer);
  const out = new Uint8Array(w * h);
  for (let y = 0; y < h; y++) for (let x2 = 0; x2 < w; x2++) {
    const i = y * w + x2;
    if (mask[i]) continue;
    if ((x2 > 0 && mask[i - 1]) || (x2 < w - 1 && mask[i + 1]) || (y > 0 && mask[i - w]) || (y < h - 1 && mask[i + w]) ||
      (x2 > 0 && y > 0 && mask[i - w - 1]) || (x2 < w - 1 && y > 0 && mask[i - w + 1]) || (x2 > 0 && y < h - 1 && mask[i + w - 1]) || (x2 < w - 1 && y < h - 1 && mask[i + w + 1])) out[i] = 1;
  }
  const sc = shadow ? c32(shadow, 200) : 0, oc = outline ? c32(outline) : 0;
  const grad = Array.isArray(fill);
  for (let y = 0; y < h; y++) {
    const t = clamp((y - pad) / Math.max(1, th - 1), 0, 1);
    const fc = c32(grad ? (fill.length === 3 ? (t < 0.5 ? mix(fill[0], fill[1], t * 2) : mix(fill[1], fill[2], (t - 0.5) * 2)) : mix(fill[0], fill[1], t)) : fill);
    for (let x2 = 0; x2 < w; x2++) {
      const i = y * w + x2;
      if (mask[i]) d[i] = fc;
      else if (out[i] && outline) d[i] = oc;
      else if (shadow && x2 > 0 && y > 0 && (mask[i - w - 1] || out[i - w - 1])) d[i] = sc;
    }
  }
  ctx.putImageData(img, 0, 0);
  if (_txt.size > 600) _txt.clear();
  _txt.set(key, cv);
  return cv;
}
function drawText(ctx, str, x, y, s, fill, align = 'center', outline = '#000', shadow = '#000') {
  const sp = textSprite(String(str), s, fill, outline, shadow);
  const dx = align === 'center' ? x - sp.width / 2 : align === 'right' ? x - sp.width : x;
  ctx.drawImage(sp, Math.round(dx), Math.round(y - sp.height / 2));
  return sp.width;
}
