// Упорядоченный дизеринг для градиентов неба
const BAYER = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5];
function ditherV(ctx, x, y, w, h, cols) {
  const img = ctx.createImageData(w, h), d = new Uint32Array(img.data.buffer);
  const cs = cols.map(c => c32(c)), n = cols.length - 1;
  for (let j = 0; j < h; j++) {
    const t = j / Math.max(1, h - 1) * n;
    const i = Math.min(n - 1, Math.floor(t)), f = t - i;
    for (let k = 0; k < w; k++) {
      const th = (BAYER[(j & 3) * 4 + (k & 3)] + 0.5) / 16;
      d[j * w + k] = f > th ? cs[i + 1] : cs[i];
    }
  }
  ctx.putImageData(img, x, y);
}

